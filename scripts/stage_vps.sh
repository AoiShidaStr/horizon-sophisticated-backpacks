#!/bin/bash
# Reproduce the launcher's trait-mod staging on the build VPS: the mod's [api]
# crate under native-api/<id>, and a generated horizon-native-game crate whose
# main links the mod's hooks() (docs/native-mods.md, "Trait mods").
set -e
WT=${WT:-/opt/build/wt/sophisticated_backpacks}
SRC=${SRC:-/opt/build/mods/sophisticated_backpacks/mixins/sophisticated_backpacks/api}
ID=sophisticated_backpacks
cd "$WT"
rm -rf native-api/$ID && mkdir -p native-api/$ID
cp -r "$SRC/src" native-api/$ID/src
sed 's|^horizon-client = .*|horizon-client = { path = "../../crates/horizon-client", default-features = false }|' \
    "$SRC/Cargo.toml" > native-api/$ID/Cargo.toml
mkdir -p crates/native-game/src
BUILD_DEPS=$(python3 - <<'PY'
import tomllib
t = tomllib.load(open("crates/horizon-client/Cargo.toml", "rb"))
out = []
for k, v in t.get("build-dependencies", {}).items():
    if isinstance(v, str):
        out.append(f'{k} = "{v}"')
    else:
        parts = []
        for kk, vv in v.items():
            if isinstance(vv, bool):
                parts.append(f'{kk} = {"true" if vv else "false"}')
            elif isinstance(vv, list):
                parts.append(f'{kk} = [' + ", ".join(f'"{x}"' for x in vv) + ']')
            else:
                parts.append(f'{kk} = "{vv}"')
        out.append(f'{k} = {{ ' + ", ".join(parts) + ' }')
print("\n".join(out))
PY
)
cat > crates/native-game/Cargo.toml <<TOML
[package]
name = "horizon-native-game"
version = "0.1.0"
edition = "2024"
publish = false
build = "../horizon-client/build.rs"

[[bin]]
name = "horizon-client"
path = "src/main.rs"

[dependencies]
horizon-client = { path = "../horizon-client", default-features = false }
horizon-threads = { path = "../horizon-threads" }
horizon-mods = { path = "../horizon-mods" }
horizon-official = { path = "../horizon-official", optional = true }
mod_0 = { path = "../../native-api/$ID", package = "mod-$(echo $ID | tr '_' '-')" }

[build-dependencies]
$BUILD_DEPS

[target."cfg(windows)".build-dependencies]
winresource = "0.1"

[features]
default = ["horizon-client/default", "official"]
official = ["dep:horizon-official"]
TOML
cat > crates/native-game/src/main.rs <<'RS'
//! Generated by the launcher (reproduced by hand for the VPS build).
#![forbid(unsafe_code)]

#[global_allocator]
static ALLOCATOR: horizon_threads::Allocator = horizon_threads::ALLOCATOR;

static MOD_API_LEVEL: [u8; horizon_mods::api_level::MARK.len()] = horizon_mods::api_level::MARK;

fn main() {
    std::hint::black_box(&MOD_API_LEVEL);
    let mods: horizon_client::mod_api::Mods = vec![
        mod_0::hooks(),
    ].into();
    horizon_client::mod_api::name_mods(&["sophisticated_backpacks"]);
    #[cfg(feature = "official")]
    horizon_official::register();
    horizon_client::entry::main_with(mods);
}
RS
python3 - <<'PY'
p = "Cargo.toml"
s = open(p).read()
for m in ['"native-api/sophisticated_backpacks"', '"crates/native-game"']:
    if m not in s:
        s = s.replace("members = [\n", "members = [\n    " + m + ",\n", 1)
open(p, "w").write(s)
PY
grep -n "native" Cargo.toml
